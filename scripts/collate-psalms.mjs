// Collate MAM (primary) against UXLC (comparison) for the imported Psalms, verse by verse.
//
//   node scripts/collate-psalms.mjs
//
// Two levels: consonants (letters only) and vowels (nikkud, cantillation removed).
// Known systematic convention differences between the editions are normalised away
// and COUNTED, never silently dropped; whatever remains is listed word by word in
// sources/wlc/COLLATION.md for a human to decide.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { stripCantillation, consonantsOf, PASEQ } from '../lib/hebrew.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const QAMATS_QATAN = '\u05C7';
const QAMATS = '\u05B8';
const HOLAM = '\u05B9';
const INVISIBLE_RE = /[\u034F\u200C\u200D]/g; // CGJ / ZWNJ / ZWJ: rendering hints, not text

// Vowel-level comparable form. Each rule is a documented convention difference:
//  - qamats qatan: MAM marks it (U+05C7), UXLC writes a plain qamats
//  - paseq / legarmeh: editions disagree on representation and spacing; not a vowel
//  - CGJ/ZWJ: UXLC rendering hints
export function vowelForm(s) {
  return stripCantillation(s)
    .replace(INVISIBLE_RE, '')
    .replaceAll(QAMATS_QATAN, QAMATS)
    .replaceAll(PASEQ, ' ')
    .normalize('NFC')
    .replace(/\s+/g, ' ')
    .trim();
}

// MAM writes the Tetragrammaton with a holam (reading convention); UXLC does not.
// Prefixed forms (לַיהֹוָה, בַּיהֹוָה, מֵיְהֹוָה) are the same convention.
const isDivineNamePair = (a, b) => consonantsOf(a).endsWith('יהוה') && a.replaceAll(HOLAM, '') === b.replaceAll(HOLAM, '');
// UXLC records the Leningrad codex's rafe (U+05BF); MAM does not use it.
const RAFE = '\u05BF';
const isRafeOnly = (a, b) => a === b.replaceAll(RAFE, '');

const words = (s) => s.split(/[ \u05BE]/).filter(Boolean);

// Pure: both editions in, report out.
export function collate(mam, uxlc) {
  const report = { consonantDiffs: [], vowelDiffs: [], conventions: { divineNameHolam: 0, rafe: 0 }, verses: 0 };
  for (const [ch, verses] of Object.entries(mam.chapters)) {
    for (const verse of verses) {
      report.verses++;
      const other = uxlc.chapters[ch]?.[String(verse.v)];
      if (other === undefined) throw new Error(`UXLC lacks Ps ${ch}:${verse.v}`);
      const ref = `${ch}:${verse.v}`;

      if (consonantsOf(verse.withNikkud) !== consonantsOf(other)) {
        report.consonantDiffs.push({ ref, mam: verse.unpointed, uxlc: consonantsOf(other) });
        continue;
      }
      const a = words(vowelForm(verse.withNikkud));
      const b = words(vowelForm(other));
      if (a.length !== b.length) {
        report.vowelDiffs.push({ ref, kind: 'word-split', mam: a.join(' '), uxlc: b.join(' ') });
        continue;
      }
      a.forEach((w, i) => {
        if (w === b[i]) return;
        if (isDivineNamePair(w, b[i])) report.conventions.divineNameHolam++;
        else if (isRafeOnly(w, b[i])) report.conventions.rafe++;
        else report.vowelDiffs.push({ ref, word: i + 1, mam: w, uxlc: b[i] });
      });
    }
  }
  return report;
}

export function readEditions() {
  return {
    mam: JSON.parse(readFileSync(join(ROOT, 'data/psalms/psalms_mam.json'), 'utf8')),
    uxlc: JSON.parse(readFileSync(join(ROOT, 'sources/wlc/psalms_wlc.json'), 'utf8')),
  };
}

function main() {
  const { mam, uxlc } = readEditions();
  const report = collate(mam, uxlc);

  const md = [
    '# Psalms collation: MAM vs UXLC',
    '',
    'Generated by `node scripts/collate-psalms.mjs`. Do not edit by hand.',
    '',
    `- MAM: git blob \`${mam.edition.source.gitBlobSha1}\``,
    `- UXLC: ${uxlc.source.citation ?? uxlc.source.url}`,
    `- Verses compared: **${report.verses}**`,
    `- Consonant differences: **${report.consonantDiffs.length}** verses`,
    `- Vowel differences (after the conventions below): **${report.vowelDiffs.length}** words`,
    '',
    '## Conventions normalised before comparing (counted, not hidden)',
    '',
    '- Cantillation and meteg removed; CGJ/ZWJ removed; NFC on both sides.',
    '- Qamats qatan (MAM U+05C7) compared as qamats.',
    '- Paseq/legarmeh ignored (representation differs between editions).',
    `- Divine name with holam (MAM) vs without (UXLC): **${report.conventions.divineNameHolam}** occurrences.`,
    `- Rafe present only in UXLC: **${report.conventions.rafe}** occurrences.`,
    '',
    'Every difference below is decided, with its witnesses, in [review.json](review.json); see [REVIEW.md](REVIEW.md).',
    '',
    '## Consonant differences',
    '',
    ...(report.consonantDiffs.length
      ? ['| ref | MAM | UXLC |', '|---|---|---|', ...report.consonantDiffs.map((d) => `| ${d.ref} | ${d.mam} | ${d.uxlc} |`)]
      : ['None.']),
    '',
    '## Vowel differences',
    '',
    ...(report.vowelDiffs.length
      ? ['| ref | word | MAM | UXLC |', '|---|---:|---|---|', ...report.vowelDiffs.map((d) => `| ${d.ref} | ${d.word ?? d.kind} | ${d.mam} | ${d.uxlc} |`)]
      : ['None.']),
    '',
  ].join('\n');

  writeFileSync(join(ROOT, 'sources/wlc/COLLATION.md'), md, 'utf8');
  console.log(`verses ${report.verses}, consonant diffs ${report.consonantDiffs.length}, vowel diffs ${report.vowelDiffs.length}, conventions ${JSON.stringify(report.conventions)}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();
